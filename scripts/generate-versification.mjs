// Regenerates src/data/versification.ts: the number of verses in every chapter
// of the 66-book canon, used to reject references that can't exist.
//
// Translations disagree on a handful of chapters (3 John 1 has 14 or 15
// verses, for example), so each count is the largest seen across the sources.
//
//   node scripts/generate-versification.mjs
//
// Set BIBLE_SOURCE_DIR to a folder of `<translation>.json` files (each a
// `/api/<translation>/complete.json` download) to run without the network.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCES = ['BSB', 'eng_kjv', 'ENGWEBP', 'eng_asv'];
const API = 'https://bible.helloao.org/api';

// prettier-ignore
const CANON = [
  'GEN', 'EXO', 'LEV', 'NUM', 'DEU', 'JOS', 'JDG', 'RUT', '1SA', '2SA', '1KI', '2KI', '1CH', '2CH', 'EZR', 'NEH',
  'EST', 'JOB', 'PSA', 'PRO', 'ECC', 'SNG', 'ISA', 'JER', 'LAM', 'EZK', 'DAN', 'HOS', 'JOL', 'AMO', 'OBA', 'JON',
  'MIC', 'NAM', 'HAB', 'ZEP', 'HAG', 'ZEC', 'MAL', 'MAT', 'MRK', 'LUK', 'JHN', 'ACT', 'ROM', '1CO', '2CO', 'GAL',
  'EPH', 'PHP', 'COL', '1TH', '2TH', '1TI', '2TI', 'TIT', 'PHM', 'HEB', 'JAS', '1PE', '2PE', '1JN', '2JN', '3JN',
  'JUD', 'REV',
];

async function load(translation) {
  const dir = process.env.BIBLE_SOURCE_DIR;
  if (dir) return JSON.parse(await readFile(join(dir, `${translation}.json`), 'utf8'));
  const response = await fetch(`${API}/${translation}/complete.json`);
  if (!response.ok) throw new Error(`${translation}: HTTP ${response.status}`);
  return response.json();
}

const counts = new Map(CANON.map((id) => [id, []]));
const disagreements = [];

for (const translation of SOURCES) {
  const data = await load(translation);
  for (const book of data.books) {
    const chapters = counts.get(book.id);
    if (!chapters) continue;
    for (const { chapter } of book.chapters) {
      const last = Math.max(0, ...chapter.content.filter((item) => item.type === 'verse').map((item) => item.number));
      const index = chapter.number - 1;
      if (chapters[index] !== undefined && chapters[index] !== last) {
        disagreements.push(`${book.id} ${chapter.number}: ${chapters[index]} vs ${last} (${translation})`);
      }
      chapters[index] = Math.max(chapters[index] ?? 0, last);
    }
  }
}

// Verse numbers that other common translations use but none of the sources do.
const ALTERNATES = [
  ['3JN', 1, 15],
  ['REV', 12, 18],
  ['2CO', 13, 14],
];
for (const [id, chapter, verses] of ALTERNATES) {
  const chapters = counts.get(id);
  chapters[chapter - 1] = Math.max(chapters[chapter - 1], verses);
}

for (const [id, chapters] of counts) {
  if (chapters.length === 0 || chapters.includes(undefined) || chapters.includes(0)) {
    throw new Error(`Incomplete verse counts for ${id}`);
  }
}

const total = [...counts.values()].reduce((sum, chapters) => sum + chapters.length, 0);
if (total !== 1189) throw new Error(`Expected 1189 chapters, found ${total}`);

const lines = [...counts].map(([id, chapters]) => `  '${id}': [${chapters.join(', ')}],`);
const output = `// Generated by scripts/generate-versification.mjs from ${SOURCES.join(', ')}. Do not edit.
// Verses per chapter; where translations differ, the largest count.
export const VERSE_COUNTS: Record<string, readonly number[]> = {
${lines.join('\n')}
};
`;

const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'data', 'versification.ts');
await writeFile(target, output);
console.log(`Wrote ${total} chapters to ${target}`);
if (disagreements.length) console.log(`Chapters where sources differ:\n  ${disagreements.join('\n  ')}`);
